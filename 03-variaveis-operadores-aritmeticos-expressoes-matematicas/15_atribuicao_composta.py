x = 5
y = 12

print(f"1) x = {5}")

# x = 5 + 12 => x = 17
x = x + y
print(f"2) x = {5} + {y} => {x}")

# x = 17 - 12 => 5
x = x - y
print(f"3) x = {17} - {y} => {x}")

# x = 5 * 12 => 60
x = x * y
print(f"4) x = {5} * {12} => {x}")

# x = 60 / 12 => 5.0
x = x / y
print(f"5) x = {60} / {12} => {x}")

# x = 5.0 % 12 => 5 = 12 * 0 + r => r = 5.0
x = x % y
print(f"6) x = {5.0} % {y} => {x}")

y = 4

# x = 5.0 ** 4 => 625.0
x = x ** y
print(f"7) x = {5.0} ** {y} => {x}")

# x = 625 // 4 => 156.0
x = x // y
print(f"x = {625} // {y} = {x}")