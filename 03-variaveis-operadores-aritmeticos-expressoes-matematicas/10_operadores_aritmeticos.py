a = 1 + (3 / 4) * 11
b = 12 * 3 - 4
c = 4 + b / 2
d = 5 - (b + c)

# 1 + (3 / 4) * 11 => 1 + 0.75 * 11 => 1 + 8.25 => 9.25
print(f"{1} + ({3} / {4}) * {11} = {a}, {type(a)}")

# 12 * 3 - 4 => 36 - 4 = 32
print(f"{12} * {3} - {4} = {b}, {type(b)}")

# 4 + 32 / 2 => 4 + 16 => 20.0
print(f"{4} + {b} / {2} = {c}, {type(c)}")

# 5 - (32 + 20.0) => 5 - 52.0 = -47.0
print(f"{5} - ({b} + {c}) = {d}, {type(d)}")